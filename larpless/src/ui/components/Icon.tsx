export type IconName = keyof typeof ICONS;

export function Icon({
  name,
  size = 18,
  color = colors.text,
  strokeWidth = 1.75,
}: {
  name: IconName;
  size?: number;
  color?: string;
  strokeWidth?: number;
}) {
  const Glyph = ICONS[name] ?? Circle;
  return <Glyph size={size} color={color} strokeWidth={strokeWidth} />;
}
